-- Владелец сам решает, сколько расходника (гель-лак и т.п.) в среднем
-- уходит на одного клиента — необязательное поле. В форме нового визита
-- (frontend/src/pages/Visits.jsx) расходники с заданной нормой показаны
-- кнопками-подсказками — мастер сам нажимает на тот, что реально
-- использовал (норм может быть несколько сразу, например разные цвета
-- геля, автоматически подставлять все сразу было бы неверно), количество
-- просто не нужно вводить руками. Ручной выбор расходника + количество
-- остаётся рабочим как раньше, для всего остального.
ALTER TABLE supplies ADD COLUMN IF NOT EXISTS default_quantity_per_visit NUMERIC(10,2);
