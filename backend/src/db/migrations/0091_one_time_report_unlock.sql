-- Исправление логической ошибки в разовой покупке (0090, тот же день) —
-- владелец указал (19.08.2026): "разовый тест" оформлялся через
-- companies.subscription_status='active', что делало его НЕОТЛИЧИМЫМ от
-- настоящей подписки — разовый платёж 1990 ₽ открывал ПОСТОЯННЫЙ доступ ко
-- всему, что даёт подписка (PDF отчётов, допечатка журналов, ИИ-советники),
-- то есть был строго выгоднее самой подписки (та же цена, но без повторных
-- списаний). Исправление: разовая покупка привязывается к КОНКРЕТНОМУ
-- отчёту (security_reports.id), не трогает subscription_status вообще —
-- открывает скачивание именно этого PDF навсегда, но не журналы и не
-- ИИ-советников (те по-прежнему требуют настоящей подписки).
ALTER TABLE security_reports ADD COLUMN IF NOT EXISTS unlocked_without_subscription BOOLEAN NOT NULL DEFAULT false;

-- NULL — обычный (рекуррентный) чек-аут подписки, как раньше. Заполнено —
-- разовая покупка конкретного отчёта, вебхук не трогает subscription_status
-- для такого платежа, только выставляет флаг выше на этом отчёте.
ALTER TABLE subscription_payments ADD COLUMN IF NOT EXISTS report_id INTEGER REFERENCES security_reports(id);
