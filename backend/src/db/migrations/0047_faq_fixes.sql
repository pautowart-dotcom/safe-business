## Сколько это стоит?

1990 ₽/мес. Первый месяц — бесплатно.

## Что будет, если не оплачу после бесплатного месяца?

Доступ к разделам блокируется — данные никуда не пропадают, вы их не
теряете, но новые записи вносить нельзя, пока не оформите подписку.
Как только оплатите — доступ возвращается сразу.

## Что будет с моими данными, если отпишусь?

Данные хранятся 30 дней на случай, если вы вернётесь, затем удаляются
безвозвратно.

## Диагностика безопасности правда бесплатная навсегда?

Да, диагностика "чего не хватает" остаётся бесплатной и честной
независимо от подписки.

## Вы советуете конкретных поставщиков (сертификация, СИЗ)?

Пока нет. В будущем возможны партнёрства, но диагностика всегда
остаётся независимой от того, воспользовались вы партнёром или нет.

## Чем Администратор отличается от Мастера в приложении?

Администратор ведёт учёт и документы по всей студии. Мастер видит и
отмечает своё личное, плюс общую сводку финансов компании на просмотр.

## Нужно ли мне самому печатать журналы?

В подписку входит генерация готового PDF с уникальным QR-кодом — его
можно скачать в любой момент. Саму печать (дома или в типографии) вы
оплачиваете отдельно, это не входит в стоимость подписки.

## Это CRM для записи клиентов?

Нет, это про безопасность и защиту от риска, не про запись клиентов.
