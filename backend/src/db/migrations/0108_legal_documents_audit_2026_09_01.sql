--
-- 1. FAQ ("Что будет с моими данными, если отпишусь?") всё ещё обещает
--    автоудаление через 30 дней — та же формулировка, что была в оферте
--    §3.3 и политике §5.3 ДО миграции 0053. 0053 поправила оферту и
--    политику (реального автоудаления в коде нет и не появится сейчас —
--    удаление только вручную, по запросу в поддержку, admin.routes.js
--    DELETE /companies/:id), но тогда забыли поправить тот же текст в
--    FAQ — тот же паттерн пропуска, что уже был между 0047 (FAQ) и 0051
--    (оферта донеслась только с задержкой). Синхронизируем формулировку.
