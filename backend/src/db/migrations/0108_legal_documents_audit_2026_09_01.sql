-- 2. Политика конфиденциальности §6 перечисляет "технических подрядчиков
--    (хостинг-провайдеры)" общей фразой, но не называет их — при этом
--    в продукте реально работают и обрабатывают персональные данные:
--    платёжный сервис ЮKassa (core/yookassa.js — получает email
--    Пользователя для формирования фискального чека на каждый платёж),
--    и сервисы Yandex Cloud: YandexGPT/Yandex AI Studio (core/
--    yandexAssist.js, core/yandexAgent.js — ИИ-ассистент и ИИ-советники
--    работают с финансовыми и клиентскими данными компании через function
--    calling, modules/ai-assistant/tools/registry.js) и Yandex Vision OCR
--    (core/documentDateExtract.js, подключён 30.08.2026 — распознаёт текст
--    с фото загружаемых документов, в т.ч. медкнижек, для автоизвлечения
--    даты). Это не новое юридическое основание и не меняет объём того, что
--    уже написано в §6.1 (обработка технических подрядчиков при соблюдении
--    ими конфиденциальности) — только называет, КТО эти подрядчики, теми
--    же словами, что уже используются в тексте. Правовую оценку того,
--    достаточно ли этого описания (нужен ли отдельный договор поручения,
