-- "Больше не используем" (18.09.2026, реальная жалоба владельца на своих
-- студиях) — расходники, которые компания перестала закупать, продолжали
-- считаться "закончившимися" (quantity <= low_stock_threshold) и светиться
-- предупреждением на главном экране бессрочно, потому что удалить их
-- нельзя (visit_supplies.supply_id -> supplies(id) ON DELETE RESTRICT,
-- уже фигурируют в истории визитов). archived_at вместо простого boolean —
-- сразу видно, когда сняли с закупки, не только сам факт; NULL = активен,
-- участвует в предупреждении о низком остатке, не NULL = архивный, скрыт
-- из предупреждения, но остаётся в общем списке и в истории визитов.
ALTER TABLE supplies ADD COLUMN IF NOT EXISTS archived_at TIMESTAMPTZ;
