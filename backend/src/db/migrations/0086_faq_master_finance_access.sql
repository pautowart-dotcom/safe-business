SET content = REPLACE(
  content,
  'Администратор ведёт учёт и документы по всей студии. Мастер видит и
отмечает своё личное, плюс общую сводку финансов компании на просмотр.',
  'Администратор ведёт учёт и документы по всей студии. Мастер видит и
отмечает только своё: свои визиты, начисленную оплату (процент,
фиксированную сумму или оплату за смену) и корректировки. Общую сводку
финансов компании видят только Администратор и Владелец.'
),
updated_at = now()
WHERE key = 'faq' AND content LIKE '%плюс общую сводку финансов компании на просмотр.%';
