SET content = replace(content,
      'Шаблоны документов - образцы (формы) документов, предоставляемые в составе Подписки.',
      'Шаблоны документов - образцы (формы) документов, предоставляемые за отдельную плату в порядке п. 3.5 Раздела 3 (на Сайте — «пакет документов»).
