-- 24.11.2026. Напоминание про один незакрытый пункт и снятие
-- бесплатного кабинета после пробного месяца.
-- «Хватит» в боте ставит stopped_at, «напомни» снимает.

CREATE TABLE IF NOT EXISTS step_reminders (
    company_id   INTEGER PRIMARY KEY REFERENCES companies(id) ON DELETE CASCADE,
    violation_id INTEGER,
    last_sent_at TIMESTAMPTZ,
    stopped_at   TIMESTAMPTZ
);

-- Оферта: п. 3.9 больше не обещает открытый кабинет без оплаты.
-- Если текст на проде уже другой, замена не сработает — это видно по 0 rows.
UPDATE legal_documents
SET content = replace(content,
      '3.9. Бесплатный доступ. Если Пробный период или оплаченный период Подписки закончился, Пользователю без оплаты остаются доступны: прохождение Теста и просмотр перечня выявленных несоответствий (без размера штрафов, ссылок на нормы и рекомендаций, кроме кратких сведений по трём наиболее значимым пунктам, которые показываются на экране и направляются на указанную почту); внесение дат в «Мои сроки» и уведомление в день наступления срока; Модуль статуса бизнеса и налогов; разовое получение сведений о своём бизнесе из открытых реестров по ИНН («Ваш бизнес снаружи», не чаще одного раза в сутки, на условиях п. 3.6.4). Заключение по результатам Теста, регулярное наблюдение за реестрами, автоматическое обновление созданных документов (без Подписки обновить документ по новой версии шаблона Пользователь может самостоятельно), уведомления заранее, ежемесячная проверка, ИИ-советник и распознавание даты по фото документа предоставляются только в рамках Подписки или Пробного периода (ИИ-советник — только в рамках Подписки). Исполнитель вправе изменять состав бесплатного доступа, сообщив об этом на Сайте.',
      '3.9. После окончания Пробного периода, подарочного доступа или оплаченного периода Подписки Личный кабинет закрывается до новой оплаты или нового подарочного доступа. Подарочный доступ действует до указанной при нём даты и сам не продлевается. Бесплатно остаются прохождение Теста и просмотр его результата (п. 18). Данные Пользователя не удаляются.'),
    updated_at = now()
WHERE key = 'user_agreement'
  AND content LIKE '%3.9. Бесплатный доступ. Если Пробный период или оплаченный период Подписки закончился%';

UPDATE legal_documents
