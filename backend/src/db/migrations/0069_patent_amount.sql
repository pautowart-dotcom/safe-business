-- "Резерв на налоги" для патента (ПСН): сумму патента мы не считаем сами
-- (зависит от региона/ниши/года, официальной таблицей не располагаем) —
-- вместо этого владелец один раз вводит уже известную ему сумму, а мы
-- считаем график оплаты по фиксированным федеральным срокам (ст. 346.51
-- НК РФ). Живёт рядом с tax_regime, а не в deadlines — это структурные
-- вводные для расчёта, а не напоминание с датой.
ALTER TABLE companies
  ADD COLUMN IF NOT EXISTS patent_start_at DATE,
  ADD COLUMN IF NOT EXISTS patent_amount NUMERIC(10,2);
