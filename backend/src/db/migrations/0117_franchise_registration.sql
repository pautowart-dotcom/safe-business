-- Франшиза на регистрации (08.09.2026, владелец: "у знакомой массаж по
-- франшизе, и это большая часть точек" — знает по крайней мере одного
-- реального пользователя-франчайзи). Существующая франшиза (0072,
-- franchise_groups) — только пост-фактум объединение уже созданных
-- компаний в сеть ради общей статистики, ничего не спрашивает на входе.
-- Здесь — отдельный, гораздо более узкий вопрос: юридически на кого
-- оформлена именно эта точка. Важно потому, что напоминания в приложении
-- адресованы "владельцу" — если точка оформлена не на человека, который
-- пользуется приложением день в день (например, франчайзи нанял
-- управляющего, а ИП/ООО оформлено на другое лицо), нужно явно
-- предупредить, а не молча считать их одним и тем же.
ALTER TABLE companies ADD COLUMN IF NOT EXISTS is_franchise BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE companies ADD COLUMN IF NOT EXISTS franchise_registered_to VARCHAR(20)
    CHECK (franchise_registered_to IN ('self', 'other'));
