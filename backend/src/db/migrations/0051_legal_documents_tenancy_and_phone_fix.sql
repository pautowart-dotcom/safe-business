-- Первый полный юридический аудит проекта (29.07.2026) — два фактических
-- расхождения между текстом документов и реальным поведением кода:
--
-- 1. Оферта §3.3 (после 0042) всё ещё описывала старую схему "только
--    просмотр 14 дней, затем архивация" при неоплате — эта же неточность
--    была уже найдена и починена в FAQ (0047_faq_fixes.sql), но тогда
--    забыли поправить оферту, где было то же самое предложение. Реальное
--    поведение — tenancy.js: жёсткая блокировка (402) сразу после
--    истечения бесплатного периода, без промежуточного read-only режима и
--    без автоматической архивации. Формулировка ниже намеренно
--    синхронизирована с уже актуальным текстом FAQ. Фраза про хранение
--    данных 30 дней при отказе от Сервиса (отписке) не трогается — это
--    не блокировка за неоплату, а отдельный сценарий, и на него код
--    автоматического удаления пока не написан вовсе (см. отчёт аудита,
--    пункт "реальный юридический риск" — это НЕ мелкая неточность текста,
--    поэтому не чиним механически, а фиксируем для владельца).
--
-- 2. Политика конфиденциальности §11.2 обещала мастеру "часть номера
--    телефона клиента вместо полного номера" — в clients.routes.js
--    (функция sanitize) мастер не видит номер телефона клиента вообще
--    (phone: null), частичного показа (последние 4 цифры) в коде больше
--    нет — комментарий в коде прямо говорит, что раньше было так, но
--    владелец решил убрать и это. Текст политики поправлен, чтобы не
--    обещать МЕНЬШУЮ защищённость данных клиента, чем есть в реальности.
--
-- WHERE ... LIKE — как в 0042/0050: не трогает документ, если владелец
-- уже отредактировал этот фрагмент вручную через админку.

UPDATE legal_documents
SET content = REPLACE(
  content,
  'При неоплате очередного периода доступ к платному функционалу
Сервиса переходит в режим "только просмотр" на 14 дней с момента
приостановки. Если оплата не поступает и в этот срок, данные
архивируются. При отказе от Сервиса (отписке) данные хранятся
30 дней на случай возврата Пользователя, после чего удаляются
безвозвратно.',
  'При неоплате очередного периода доступ к платному функционалу
Сервиса блокируется — новые записи вносить нельзя, пока не будет
оформлена оплата; уже внесённые данные Пользователя при этом не
удаляются и не архивируются автоматически, доступ возобновляется
сразу после поступления оплаты. При отказе от Сервиса (отписке)
данные хранятся 30 дней на случай возврата Пользователя, после чего
удаляются безвозвратно.'
),
updated_at = now()
WHERE key = 'oferta' AND content LIKE '%переходит в режим "только просмотр" на 14 дней%';

