-- Первый полный аудит кибербезопасности проекта (29.07.2026), два фикса
-- со схемой БД:
--
-- 1. password_changed_at — компани-токен и базовый токен живут 30 дней
--    (core/jwt.js) без отзыва. При сбросе пароля через /reset-password
--    старые уже выданные токены раньше продолжали работать до истечения
--    срока — теперь requireAuth сверяет момент выдачи токена (iat) с этим
--    полем и отклоняет токены, выданные до последней смены пароля.
-- 2. password_reset_tokens.token_plain — временное решение из 0041, пока
--    не было реальной отправки почты (ссылку смотрел Super Admin вручную
--    через админку). Реальная отправка (Yandex SMTP, core/mailer.js) уже
--    подключена и используется — колонка с паролем восстановления в
--    открытом виде и роут её просмотра (GET /admin/password-resets)
--    стали чистым легаси с риском без пользы. Убираем, как и было
--    запланировано в комментарии 0041.

ALTER TABLE users ADD COLUMN IF NOT EXISTS password_changed_at TIMESTAMPTZ;
ALTER TABLE password_reset_tokens DROP COLUMN IF EXISTS token_plain;
