-- Точечные REPLACE по уникальным фразам, а не перезапись всего документа —
-- так видно ровно, что изменилось, и WHERE ... LIKE не тронет текст, если
-- он уже отредактирован вручную через админку (тот же принцип, что в 0042).
--
-- [Юрист: ...] пометки (переход ИП→ООО, поштучная оплата филиалов, политика
-- возвратов, ограничение ответственности, оператор ПДн клиентов студий,
-- cookie-баннер) — НЕ трогаем, это вопросы для юридической проверки, не
-- реквизиты.

