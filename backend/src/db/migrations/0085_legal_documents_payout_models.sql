-- Три модели оплаты мастера (0084_payout_models.sql, 15.08.2026) добавили
-- фиксированную сумму за визит/услугу и фиксированную сумму за смену
-- (master_shifts) в дополнение к проценту от чека, который единственный
-- был назван в политике конфиденциальности §2.1 ("проценты выплат"). Это
-- чисто фактическая правка перечня категорий данных — не меняет смысла
-- пункта, не требует юридической оценки: то же по характеру расхождение,
-- что чинили точечным REPLACE в 0042/0050/0051/0053.
--
-- WHERE ... LIKE — не тронет документ, если владелец уже отредактировал
-- этот фрагмент вручную через админку.

UPDATE legal_documents
SET content = REPLACE(
  content,
  '- финансовые данные, связанные с расчётом заработной платы
  (проценты выплат, история корректировок);',
  '- финансовые данные, связанные с расчётом заработной платы
  (проценты выплат, фиксированные суммы за визит/услугу, фиксированные
  суммы за рабочую смену, история корректировок);'
),
updated_at = now()
WHERE key = 'privacy_policy' AND content LIKE '%(проценты выплат, история корректировок);%';
