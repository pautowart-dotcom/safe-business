-- Юридический аудит 26.08.2026 — два точечных фактических расхождения между
-- текстом документов и реальным поведением кода (не требуют юридической
-- оценки, только сверки с фактами, тот же принцип, что 0051/0053/0085):
--
-- 1. Оферта §3.3 (после 0051/0053) и FAQ (после 0047) описывают блокировку
--    за неоплату словами "новые записи вносить нельзя" — это читается так,
--    будто просмотр уже внесённых данных остаётся доступен. По факту
--    requireTenant (core/middleware/tenancy.js) отвечает 402 на ЛЮБОЙ запрос
--    закрытой компании кроме /platform/companies/current и
--    /platform/subscription — то есть ни один раздел приложения открыть
--    нельзя вообще, включая просмотр, а axios-интерцептор (frontend/src/
--    api/client.js) на этот 402 сразу перекидывает браузер на /lk/subscription.
--    Формулировка правится на "полностью блокируется / открыть раздел
--    нельзя", без изменения по сути (сами данные как не удалялись, так и не
--    удаляются — это уже верно).
--
-- 2. Оферта §4.1 (никогда не правилась с 0013) по-прежнему обещает
--    "шифрование данных аудита безопасности бизнеса" без оговорок — тот же
--    факт уже был исправлен в Политике конфиденциальности §8.2 миграцией
--    0053 (шифруются только ответы/баллы — answer_index_enc/points_enc в
--    0024_security_answers_encryption.sql; код нарушения и итоговый индекс
--    пока не зашифрованы). Здесь просто синхронизируем оферту с уже
--    исправленной формулировкой политики, не решаем ничего нового.
--
-- WHERE ... LIKE — как во всех предыдущих миграциях этого рода: не тронет
-- документ, если владелец уже отредактировал этот фрагмент вручную через
-- админку.

