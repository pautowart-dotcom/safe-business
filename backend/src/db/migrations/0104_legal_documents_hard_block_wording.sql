оформлена оплата; уже внесённые данные Пользователя при этом не
удаляются и не архивируются автоматически, доступ возобновляется
сразу после поступления оплаты.',
  'Сервиса полностью блокируется — открыть ни один раздел Сервиса,
включая просмотр уже внесённых данных, нельзя, пока не будет
оформлена оплата; сами данные Пользователя при этом не удаляются и
не архивируются автоматически, доступ возобновляется сразу после
поступления оплаты.'
),
