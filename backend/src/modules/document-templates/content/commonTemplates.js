const COMMON_KINDS = Object.keys(KINDS);

// виды документов ниши: без niches — во всех, с niches — только в перечисленных
function kindsFor(niche) {
  return COMMON_KINDS.filter((kind) => !KINDS[kind].niches || KINDS[kind].niches.includes(niche));
}

function build(niche, kind) {
  const k = KINDS[kind];
  return {
    key: `${niche}_${kind}`,
    niche,
    title: typeof k.title === 'function' ? k.title(niche) : k.title,
    pdfTitle: k.pdfTitle,
    ...DRAFT,
    lawReference: typeof k.lawReference === 'function' ? k.lawReference(niche) : k.lawReference,
    employerOnly: k.employerOnly,
    documentCategory: k.documentCategory,
    fields: typeof k.fields === 'function' ? k.fields(niche) : k.fields,
    body: k.body(niche),
    prepare: k.prepare,
  };
}

module.exports = { build, COMMON_KINDS, kindsFor, NICHE_GROUP };
