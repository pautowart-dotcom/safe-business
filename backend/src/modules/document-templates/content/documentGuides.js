function hasWebsiteField(template) {
  return Array.isArray(template.fields) && template.fields.some((f) => f.key === 'website');
}

function guideFor(template) {
  if (!template || !template.key) return { ...FALLBACK, siteFile: false };
  const found = GUIDES.find((g) => template.key.endsWith(g.suffix));
  if (found) {
    const { suffix, ...guide } = found;
    return { siteFile: false, ...guide };
  }
  if (template.key.endsWith('_pd_consent')) {
    return hasWebsiteField(template) ? { ...SITE_CONSENT } : { ...PAPER_OR_PARENT_CONSENT, siteFile: false };
  }
  return { ...FALLBACK, siteFile: false };
}

function websiteProblem(template, values) {
  const guide = guideFor(template);
  if (!guide.siteFile) return null;
  const raw = String((values && values.website) || '').trim();
  if (NONE_SITE.test(raw)) {
    return `«${template.title}» не собираем: своего сайта нет. Этот файл — для вашей страницы. Ссылку на запись в него не вставляем.`;
  }
  if (BOOKING_PAGE.test(raw)) {
    return `«${template.title}» не собираем: в поле «сайт» указана страница записи. Ссылку на Дикиди и другую онлайн-запись в этот файл не вставляем.`;
  }
  return null;
}

function websiteProblems(templates, values) {
  return templates.map((t) => websiteProblem(t, values)).filter(Boolean);
}

// Пакет: файл «для сайта» со страницей записи или без своего сайта не собираем.
// Остальные бумаги пакета собираем.
function packSplit(templates, values) {
  const skipped = [];
  const keep = [];
  for (const template of templates) {
    const problem = websiteProblem(template, values);
    if (problem) skipped.push(problem);
    else keep.push(template);
  }
  return { keep, skipped };
}

