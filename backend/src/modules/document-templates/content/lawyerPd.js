function purposesBlock(values) {
  const list = PURPOSES.filter((p) => !p.flag || values[p.flag] === 'yes');
  // Своя цель — ввод пользователя: без переносов, чтобы не создать раздел.
  const oneLine = (s) => String(s || '').replace(/\r\n|\r|\n/g, ' ').replace(/^[#\-\s]+/, '').trim();
  const extra = oneLine(values.extraPurpose);
  const extraData = oneLine(values.extraPurposeData);
  if (extra && extraData) {
    list.push({
      title: extra,
      subjects: 'Пользователи сайта; Клиенты',
      data: extraData,
      method: 'Смешанная',
      term: 'Персональные данные обрабатываются до момента отзыва согласия на обработку персональных данных',
      end: 'Персональные данные подлежат уничтожению в течение 30 дней с момента поступления отзыва согласия на обработку персональных данных',
    });
  }
  return list
    .map((p, i) => `# Цель ${i + 1}. ${p.title}

- Категории субъектов ПДн: ${p.subjects}
- Перечень обрабатываемых ПДн: ${p.data}
- Способ обработки ПДн: ${p.method}
- Сроки обработки и хранения ПДн: ${p.term}
- Действия с ПДн по окончании обработки: ${p.end}`)
    .join('\n\n');
}

