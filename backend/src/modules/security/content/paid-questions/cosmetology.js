const toCosmetologyCode = (code) => code.replace(/^MS-/, 'CS-');

// Вопрос массажа без специфики массажа в тексте — список кодов ниже
// проверен вручную.
function fromMassage(msCode) {
  const source = massage.questions.find((q) => q.code === msCode);
  if (!source) throw new Error(`cosmetology: в paid-questions/massage.js нет вопроса ${msCode}`);
  return {
    ...source,
    code: toCosmetologyCode(msCode),
    answers: source.answers.map((a) => (
      a.violationCodeOverride ? { ...a, violationCodeOverride: toCosmetologyCode(a.violationCodeOverride) } : { ...a }
    )),
  };
}

