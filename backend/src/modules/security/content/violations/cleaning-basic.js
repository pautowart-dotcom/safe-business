//   depilation.js/solarium.js):
//   • Обязательность медкнижек для клинеров — неясно, особенно для бытового
//     (квартиры) клининга. Вторичные источники ссылаются на Приказ
//     Минздравсоцразвития №302н, частично заменённый Приказом Минздрава
