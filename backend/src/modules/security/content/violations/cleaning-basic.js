//     подтверждён — в отличие от бьюти-ниш, где это подтверждено. См. CL-102.
//   • Готового единого санитарного норматива под клининг как отрасль НЕ
//     существует — нормы скомпонованы из общих актов (52-ФЗ, ТК РФ про
