//   третьим лицам требует лицензии Роспотребнадзора (194-ФЗ от 29.05.2023,
//   ПП РФ №337 от 20.03.2024). Обычная уборка с обработкой антисептиком —
//   НЕ то же самое, что "услуга дезинфекции", но граница размыта на
//   практике (формулировки в прайсе/рекламе имеют значение) — см. CL-201,
//   намеренно нейтральная формулировка, не создающая нарушение для обычной
//   уборки, только для случая, где дезинфекция продаётся как отдельная
//   услуга.
// — Проф.химия (дезсредства) требует СГР (свидетельство о государственной
//   регистрации, Решение КТС №299 от 28.05.2010), а НЕ сертификат/декларацию
//   ЕАС по ТР ТС, как расходники в маникюре (см. MN-304) — другой тип
//   документа. См. CL-202.
// — Ответственность за порчу имущества клиента при уборке — договорной
//   блок (ГК РФ, ФЗ №2300-1), которого в таком виде нет у бьюти-ниш (там
//   клиент не оставляет мастера одного в своей квартире/офисе с ценным
//   имуществом) — см. CL-104, новый пункт, не имеющий аналога в других
//   нишах.
// — Спецклининг после ремонта/пожара — лицензия Росприроднадзора на отходы
//   I-IV класса (89-ФЗ) — НЕ включено в эту нишу, см. CL-801.
