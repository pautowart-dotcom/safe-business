// Пункт массажа с тем же смыслом под кодом CS-. Берём только пункты без
// специфики массажа в тексте — список кодов ниже проверен вручную.
function fromMassage(msCode) {
  const source = massage.violations.find((v) => v.code === msCode);
  if (!source) throw new Error(`cosmetology: в massage.js нет пункта ${msCode}`);
  return { ...source, code: msCode.replace(/^MS-/, 'CS-'), howTo: [...source.howTo] };
}

// Пункт другой ниши без её специфики в тексте (жилое помещение — у
// маникюра, индикаторы стерилизации — у тату), код заменён на CS-.
function fromNiche(source, code, csCode) {
  const item = source.violations.find((v) => v.code === code);
  if (!item) throw new Error(`cosmetology: нет пункта ${code}`);
  return { ...item, code: csCode, howTo: [...item.howTo] };
}

