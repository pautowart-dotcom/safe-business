// — КЛЮЧЕВАЯ, РЕАЛЬНО НАЙДЕННАЯ И ПОДТВЕРЖДЁННАЯ ПЕРВОИСТОЧНИКОМ СПЕЦИФИКА
//   НИШИ — ст. 13 ФЗ от 27.12.2018 №498-ФЗ «Об ответственном обращении с
//   животными»: выгул потенциально опасной собаки без намордника и поводка
//   ЗАПРЕЩЁН НЕЗАВИСИМО ОТ МЕСТА выгула, за исключением огороженной
//   территории в собственности владельца с предупреждающей надписью. Список
//   пород утверждён Постановлением Правительства РФ от 29.07.2019 №974 —
//   12 пород и их метисы (акбаш, американский бандог, амбульдог,
//   бразильский бульдог, булли кутта, бульдог алапахский чистокровный/отто,
//   бэндог, волко-собачьи гибриды, волкособ, гуль дог, питбульмастиф,
//   северокавказская собака). Штраф — ст. 8.52 КоАП РФ: граждане 1500–3000₽,
//   должностные лица 5000–15000₽, юрлица 15000–30000₽. Правило касается
//   именно занятий на улице/в парке — типичный формат работы кинолога —
//   поэтому прямо применимо к этой нише, не абстрактная норма про владельцев.
// — «Кинолог»/инструктор по дрессировке — НЕ лицензируемая и не
