// блокирующей развилки, что стоматология (см.
// project_dental_niche_research_2026_09_09) — не тихая адаптация, а решение
// владельца, зафиксировано отдельно в памяти, содержание сюда не попало.
//
// Источники разведки (WebSearch, 15.09.2026):
// — ОКВЭД: 43.99 «Работы строительные специализированные прочие, не
//   включённые в другие группировки» или 43.34 «Производство малярных и
//   стекольных работ» (включает мойку и остекление фасадов) — оба
//   встречаются на практике, точный выбор зависит от позиционирования
//   (чисто мойка vs. более широкий фасадный сервис).
// — ЛИЦЕНЗИЯ САМОГО БИЗНЕСА НЕ ТРЕБУЕТСЯ — в отличие от дезинфекционной
//   деятельности (см. выше), работы на высоте регулируются как требования
//   охраны труда к КВАЛИФИКАЦИИ ПЕРСОНАЛА (группы допуска, обучение), а не
//   как лицензируемый вид деятельности юрлица — та же логика различия, что
//   у tire_service/auto_service с подъёмниками (техническое требование к
//   работнику/оборудованию ≠ лицензия на бизнес).
// — КЛЮЧЕВАЯ, РЕАЛЬНО НАЙДЕННАЯ СПЕЦИФИКА НИШИ — Приказ Минтруда России от
//   16.11.2020 №782н (ред. от 29.04.2025) «Правила по охране труда при
//   работе на высоте»: 3 группы допуска персонала (объём обучения/права
//   зависят от группы), обязательное оформление наряда-допуска на
//   производство работ на высоте, удостоверение о допуске к высотным
//   работам.
// — ПЕРИОДИЧЕСКИЕ МЕДОСМОТРЫ (FC-503) — как и в kids_club, здесь требование
