// каждая процедура тату/пирсинга/ПМ — это прокол или травмирование кожи,
// поэтому стерилизация, одноразовые иглы и отходы класса Б — не один пункт
// из многих, а центральный риск ниши. Блок 8 — специфика именно этой ниши
// (информированное согласие, возраст, спорный статус лицензирования пирсинга
