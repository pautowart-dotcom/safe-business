// источниками:
// — художественная (декоративная) татуировка — бытовая услуга, отдельная
//   медицинская лицензия не требуется (согласована позиция Минздрава и
//   практика рынка);
// — пирсинг: статус СПОРНЫЙ — ГОСТ Р 59454-2021 относит его к бытовым
//   услугам, но Приказ Минздрава РФ от 13.10.2017 №804н включает пирсинг в
//   номенклатуру медицинских услуг, и по ряду источников контролирующие
//   органы (Роспотребнадзор, прокуратура) на практике склонны опираться на
//   номенклатуру Минздрава — см. TT-803, требует юридической консультации;
// — перманентный макияж (дермапигментация): статус СПОРНЫЙ — Минздрав
//   допускает выполнение косметического татуажа немедицинским персоналом с
//   парфюмерно-косметическими средствами, но решение Верховного Суда РФ от
//   06.03.2023 отнесло дермапигментацию к медицинским услугам — см. TT-804,
//   требует юридической консультации, однозначного ответа в открытых
//   источниках нет;
// — удаление татуировок лазером — однозначно медицинская услуга, требует
//   медицинской лицензии (консенсус источников) — см. TT-805;
// — красители/пигменты для тату и ПМ регулируются ТЕМ ЖЕ регламентом, что и
//   обычная косметика — ТР ТС 009/2011 (через декларацию или свидетельство о
//   государственной регистрации — СГР, а не сертификат) — гипотеза из
//   задания не подтвердилась, регламент общий;
