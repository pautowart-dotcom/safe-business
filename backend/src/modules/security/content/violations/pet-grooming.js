// только о клиенте (владельце), но и о питомце — отсюда GR-105 (анкета о
// питомце) вместо привычной приёмной квитанции.
//
// Источники разведки (WebSearch, 12.09.2026):
// — Груминг (ОКВЭД 01.42 «Предоставление услуг в области животноводства,
//   кроме ветеринарных услуг» и/или 96.09) прямо ОТДЕЛЁН от ветеринарной
//   деятельности — стрижка/уход не требуют лицензии, в отличие от
//   диагностики/лечения/вакцинации (лицензируемая ветеринарная
//   деятельность, 99-ФЗ). Подтверждено несколькими независимыми
//   источниками — эта ниша НЕ несёт лицензионного риска клининга/химчистки.
// — Применимость ОКВЭД 96.09 к уведомительному порядку ПП №584 НЕ
//   подтверждена однозначно (в отличие от ателье/обуви/фотостудии/
//   химчистки, где Приложение №1 прямо называет «бытовые услуги») — честно
//   помечено как требующее проверки, см. GR-102.
// — Специального СанПиН именно для груминг-салонов НЕ существует (в отличие
//   от когда-то существовавшего, но отменённого СанПиН 2.2.2506-09 для
//   химчисток) — один найденный вторичный источник (wikizoo.ru) ошибочно
//   ссылался на «СанПиН 2.1.2.1199-03» как на норматив для груминга, но при
//   проверке этот номер оказался документом про ПАРИКМАХЕРСКИЕ для людей
//   (утверждён 2003, давно заменён на СП 2.1.3678-20 в общем порядке) —
//   НЕ используется здесь как источник, та же дисциплина проверки, что
//   спасла от белорусского источника при работе над ремонтом обуви.
//   Санитарная база — общий СП 2.1.3678-20 (раздел про бытовые услуги),
//   заменяется на СП 2.1.4284-26 с 01.09.2026, та же оговорка, что у
//   остальных ниш проекта.
// — Животные по ст. 137 ГК РФ подчиняются общим правилам об имуществе,
//   ЗА ИСКЛЮЧЕНИЕМ случаев, когда закон или иные правовые акты
