// Рекомендация юрформы для интейка продукта "roadmap открытия бизнеса" —
// используется, когда человек выбрал "не знаю, помогите выбрать" и ответил
// на 2-3 вопроса. Факты проверены 10.08.2026 (law-compliance-monitor):
// - лимит дохода на НПД (самозанятость) — 2 400 000 ₽/год, не менялся с
//   момента введения налога, 422-ФЗ (при превышении право на НПД теряется
//   автоматически с начала месяца превышения);
// - самозанятый не может нанимать людей по трудовому договору — ст. 4 422-ФЗ
//   (только договоры ГПХ, и то с риском переквалификации при регулярной
//   работе с одним и тем же человеком — см. buildRoadmap.js, код "-502");
// - совладельцем можно оформить только ООО — у самозанятого и ИП всегда
//   один собственник-физлицо.
const SELF_EMPLOYED_INCOME_LIMIT_RUB = 2_400_000;

function recommend({ hasEmployees, hasCoOwners, expectedAnnualIncomeRub }) {
  if (hasCoOwners) {
    return {
      legalForm: 'ooo',
      explanation: 'У вас несколько совладельцев — оформить бизнес на нескольких человек можно только через ООО: у самозанятого и ИП всегда один собственник-физлицо.',
    };
  }
  if (hasEmployees) {
    return {
      legalForm: 'ip',
      explanation: 'Вы планируете нанимать сотрудников — самозанятому нанимать людей по трудовому договору нельзя (ст. 4 422-ФЗ). ИП подходит: один собственник, но можно официально нанимать персонал.',
    };
  }
  if (expectedAnnualIncomeRub != null && expectedAnnualIncomeRub > SELF_EMPLOYED_INCOME_LIMIT_RUB) {
    return {
      legalForm: 'ip',
      explanation: `Ожидаемый доход выше ${SELF_EMPLOYED_INCOME_LIMIT_RUB.toLocaleString('ru-RU')} ₽/год — это лимит для самозанятости (НПД). При превышении право на этот режим теряется автоматически, поэтому лучше сразу открыть ИП.`,
    };
  }
  return {
    legalForm: 'self_employed',
    explanation: `Вы работаете один(-а), без сотрудников, и ожидаемый доход в пределах ${SELF_EMPLOYED_INCOME_LIMIT_RUB.toLocaleString('ru-RU')} ₽/год — самозанятость (НПД) самый быстрый и дешёвый вариант для старта: регистрация через приложение «Мой налог» занимает несколько минут. Если планы изменятся (наймёте сотрудников или доход вырастет) — можно позже перейти на ИП.`,
  };
}

module.exports = { recommend, SELF_EMPLOYED_INCOME_LIMIT_RUB };
