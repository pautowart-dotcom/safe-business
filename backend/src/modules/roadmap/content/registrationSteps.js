// Шаги регистрации самой юрформы — общие для всех 4 ниш, зависят только от
// выбора самозанятый/ИП/ООО. Не пересекается с violations/<niche>.js (там —
// требования к уже действующему бизнесу вроде аренды/уведомления/санитарии,
// см. buildRoadmap.js); здесь — именно создание юрлица/статуса.
//
// Факты проверены 10.08.2026 (law-compliance-monitor + WebSearch), под
// вопросом остаётся один нюанс (отмечен ниже) — нужен ли нотариус ООО с
// несколькими учредителями, если не у всех есть личная УКЭП; это уточнено
// в описании, не заявлено как жёсткое правило.
function registrationItems(legalForm) {
  if (legalForm === 'self_employed') {
    return [
      {
        title: 'Зарегистрироваться как самозанятый (НПД)',
        description: 'Через приложение «Мой налог» или Госуслуги. Госпошлина не взимается, платить вперёд не нужно.',
        durationNote: 'обычно в течение дня',
      },
    ];
  }

  if (legalForm === 'ip') {
    return [
      {
        title: 'Подать заявление на регистрацию ИП',
        description: 'Через Госуслуги или личный кабинет ФНС. При подаче в электронном виде госпошлина не взимается (0 ₽ вместо 800 ₽ на бумаге).',
        durationNote: '3 рабочих дня с момента подачи (п. 3 ст. 22.1 129-ФЗ)',
      },
      {
        title: 'Если планируете патент (ПСН) — подать заявление заранее',
        description: 'Необязательный шаг: только если решите работать на патенте, а не на УСН/НПД. Заявление подаётся не позднее чем за 10 рабочих дней до даты начала действия патента. Стоимость патента зависит от региона — уточните в личном кабинете ФНС перед подачей, единой федеральной цифры нет.',
        durationNote: 'подать за 10 рабочих дней до старта; налоговая отвечает за 5 рабочих дней (ст. 346.45 НК РФ)',
      },
    ];
  }

  // ooo
  return [
    {
      title: 'Подготовить документы на регистрацию ООО',
      description: 'Устав, решение (один учредитель) или протокол (несколько учредителей) о создании, заявление Р11001. Уставный капитал — от 10 000 ₽, вносится деньгами (ст. 14 14-ФЗ).',
      durationNote: null,
    },
    {
      title: 'Подать заявление на регистрацию ООО',
      description: 'Если у всех учредителей есть личная УКЭП — можно подать полностью электронно, госпошлина не взимается (0 ₽ вместо 4000 ₽ на бумаге). Если УКЭП есть не у всех — обычно требуется участие нотариуса; уточните точный порядок в вашей налоговой или у нотариуса заранее, чтобы не терять время в очереди.',
      durationNote: '3 рабочих дня с момента подачи (п. 3 ст. 13 129-ФЗ)',
    },
  ];
}

module.exports = { registrationItems };
