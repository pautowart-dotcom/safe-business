// Что ответить клиенту и нужно ли звать человека. Сценарии —
// docs/studio-bot/scenarii.md. Здоровье, опоздание, переделка, жалоба, отмена,
// «куда я записана» — готовым ответом без ИИ (templateAnswer). Остальное
// предлагает ИИ, код страхует: цены и ссылки только из базы.
// Любой сбой ИИ → «администратор подключится».
const { localParts, inWorkHours, replyPromise } = require('./hours');

const HANDOFFS = ['none', 'normal', 'urgent', 'lead'];
const RANK = { none: 0, normal: 1, lead: 1, urgent: 2 };

const RE_LATE = /опазд|опоздаю|опоздаем|задерж(иваюсь|усь|имся)|буду позже|не успеваю к/i;
const RE_HEALTH = /аллерг|беремен|кормлю грудью|грибок|микоз|травм|воспал|нарыв|гно[йя]|кровоточ|дермат|экзем|псориаз|диабет/i;
const RE_REPAIR = /переделать|переделк|отслоил|отклеил|сломал(ся|ась|ись)|надлом|слез(ло|ли|ла) через/i;
const RE_COMPLAINT = /жалоб|недоволь|не понравил|ужасн|кошмар|верните|вернуть деньги|возврат/i;
const RE_CANCEL = /отмените|отменить|отменяю|отмена записи|не смогу прийти|не получится прийти|не приду/i;
const RE_CANCEL_NOT = /не отмен|почему отмен|перен[её]с|перенос/i; // «не отменяйте», «почему отменили», «отменить или перенести» — пусть разбирает ИИ
const RE_OWN_BOOKING = /(куда|в какую|в которую|в какой|какую студию|на какой адрес|где).{0,30}записан|записывал|забыл.{0,30}(запис|время|студи|адрес)|(во сколько|на когда|на какое время|к какому мастеру) я записан/i;

// Ситуации, где ответ всё равно шаблонный и дальше подключается администратор, —
// без ИИ, чтобы не платить за запрос. Порядок важен: здоровье и опоздание первыми.
function templateAnswer(text, promise) {
  const admin = `Администратор подключится ${promise}`;
  const t = (topic, handoff, reply) => ({ reply, handoff, topic, summary: '', gap: '', attach: '', waitlist: null, guard: 'template' });
  if (RE_HEALTH.test(text)) return t('здоровье', 'normal', `Это лучше обсудить с мастером. ${admin}.`);
  if (RE_LATE.test(text)) return t('опоздание', 'urgent', 'Спасибо, что предупредили! Передал мастеру. Если поймёте, что удобнее перенести, — администратор на связи и поможет.');
  if (RE_REPAIR.test(text)) return t('переделка', 'urgent', `Мы постараемся максимально оперативно решить ваш вопрос — ${admin.toLowerCase()}.`);
  if (RE_COMPLAINT.test(text)) return t('жалоба', 'urgent', `Нам очень жаль, что так вышло. Пришлите, пожалуйста, фото — мы постараемся максимально оперативно решить ваш вопрос, ${admin.toLowerCase()}.`);
  if (RE_CANCEL.test(text) && !RE_CANCEL_NOT.test(text)) return t('отмена', 'normal', `Спасибо, что предупредили заранее! Для нас важно каждое окошко — теперь мы сможем предложить его тому, кто его ждёт. ${admin} и отменит запись. Будем рады видеть вас, когда будет удобно 🤍`);
  if (RE_OWN_BOOKING.test(text)) return t('своя запись', 'normal', `${admin} и подскажет.`);
  return null;
}

// Приветствие в первом ответе ставит код — ИИ то забывал поздороваться,
// то здоровался по-своему. Если в ответе зовём человека, про администратора
// скажет сам ответ; в жалобе, опоздании и здоровье — без 🤍.
function greeting(config, now = new Date(), { handoff = 'none', topic = '' } = {}) {
  const warm = handoff !== 'urgent' && topic !== 'здоровье';
  const hello = `Здравствуйте! На связи бот-помощник Службы заботы — для максимально оперативной помощи${warm ? ' 🤍' : '.'}`;
  if (handoff !== 'none') return hello;
  return `${hello}\nАдминистратор тоже на связи и, если понадобится, подключится ${replyPromise(config, now)}.`;
}

// Если ИИ всё-таки поздоровался или представился сам — убираем, чтобы не было двух приветствий.
const RE_HELLO = /^(здравствуйте|добрый (день|вечер)|доброе утро|доброй ночи|привет)[^.!?\n🤍]*[.!?]*\s*/iu;
const RE_INTRO = /^(это|на связи)[^.!?\n🤍]*(служб[аы] заботы|фабрик)[^.!?\n🤍]*[.!?]*\s*(🤍\s*)?/iu;

function stripGreeting(reply) {
  return reply.replace(RE_HELLO, '').replace(RE_INTRO, '').replace(/^🤍\s*/, '').trim();
}

function systemPrompt({ config, kbText, styleText, now, clientName, firstReply }) {
  const promise = replyPromise(config, now);
  return `Ты — ${config.botName}. Отвечаешь клиентам маникюрной студии в Telegram от имени студии.
Сейчас: ${localParts(now, config.timezone).label} (${inWorkHours(config, now) ? 'рабочее время' : 'нерабочее время'}).
Когда зовёшь человека, пиши так: «Администратор подключится ${promise}». Не пиши «передал администратору, ответим …» и «спасибо за уточнение».
Имя клиента в Telegram: «${clientName || 'не указано'}».

БАЗА СТУДИИ — единственный источник фактов:
<<<
${kbText || '(база пока пустая)'}
>>>

СТИЛЬ ОБЩЕНИЯ — как писать (факты отсюда не бери, только тон и манеру):
<<<
${styleText || '(не задан)'}
>>>
${firstReply ? '\nЭто ПЕРВЫЙ ответ клиенту в этом диалоге. Приветствие и представление бот добавит сам — не здоровайся и не представляйся, начни сразу с сути. Если клиент только поздоровался — ответь «Подскажу по услугам, ценам и записи — что вас интересует?».\n' : '\nДиалог уже идёт — не здоровайся заново и не представляйся.\n'}
Правила:
1. Цены, адреса, часы, правила, акции, ссылки — только из базы, слово в слово. Адрес всегда полностью, как в базе: улица, дом и корпус («Большая Марфинская, д. 4, к. 7»), не просто название улицы. Цену называй как в базе (с «от», если там «от») и добавляй, что точнее скажет мастер. Чего нет в базе — не придумывай: «Уточню у администратора — он подключится ${promise}», handoff "normal", и в "gap" коротко запиши, какой информации не хватило (например «есть ли детский маникюр»), без имён, телефонов и дат клиента.
1а. Про цены на маникюр всегда коротко объясни пакетную систему (в цену пакета уже входит всё из описания, складывать ничего не нужно). Цены всегда списком: каждая услуга с новой строки «• Услуга — цена», без описаний и длительности. Спрашивают цены в общем («прайс», «какие цены») — весь прайс, маникюр и педикюр отдельными блоками. Спрашивают «сколько стоит маникюр» или «педикюр» — только этот блок. В конце одна фраза: «Подсказать, чем отличаются пакеты?» или что точнее скажет мастер. Что входит в пакет — рассказывай, только когда спросили «что входит», «чем отличаются» или про один конкретный пакет, и тоже коротко.
2. Свободные окна и время ты не знаешь. Новому клиенту для записи сразу дай ссылку на онлайн-запись из базы. Если непонятно, какая студия, — не спрашивай, а сразу дай обе ссылки, подпись — полный адрес (каждую с новой строки: «Большая Марфинская, д. 4, к. 7 — ссылка», «Ивовая улица, д. 6, к. 1 — ссылка»). Никогда не пиши «хотите, отправлю ссылку?» — просто отправляй. Фразу «Мы работаем только по предварительной записи» пиши ТОЛЬКО когда прямо спрашивают, можно ли прийти без записи. Не пиши её, когда клиент уже записан, просит другое время, переделку или ремонт ногтя. Если клиент пишет, что по ссылке не получается или нужно срочно сегодня, — handoff "normal". Если окон на нужное время нет, хочет раньше или к конкретному мастеру, а у него всё занято, — правило 15.
3. Не обещай «запишем», «исправим», «вернём деньги». Только «Администратор подключится ${promise}».
4. Клиент уже записан и не успевает, просит другое время или окошко попозже, хочет перенести — максимально лояльно: начни с «Спасибо, что предупредили!», затем «Вы можете сами изменить запись по ссылке:» и ссылки (нужной студии или обе, с полными адресами), в конце «Если удобнее, администратор поможет — он на связи и подключится ${promise}». Не расспрашивай про дату и время, не пиши про предварительную запись. handoff "normal".
4а. Отмена: «Спасибо, что предупредили заранее! Для нас важно каждое окошко — теперь мы сможем предложить его тому, кто его ждёт.» Без уговоров и упрёков. Если дата и время записи неизвестны ни из переписки, ни из автосообщения Dikidi — в том же сообщении спроси их, handoff "none". Известны или клиент не хочет уточнять — допиши «Администратор подключится ${promise} и отменит запись. Будем рады видеть вас, когда будет удобно 🤍», handoff "normal".
5. Клиент опаздывает — «Спасибо, что предупредили! Передал мастеру. Если поймёте, что удобнее перенести, — администратор на связи и поможет.» handoff "urgent".
6. Здоровье (аллергия, беременность, грибок, травма, воспаление, лекарства) — не советуй и не расспрашивай: «Это лучше обсудить с мастером. Администратор подключится ${promise}», handoff "normal".
7. Переделка или ремонт ногтя (сломался, надломился, отслоилось) — без «предварительной записи», без ссылок и без «хотите записаться?»: «Мы постараемся максимально оперативно решить ваш вопрос — администратор подключится ${promise}.» Жалоба, недовольство, возврат — коротко посочувствуй, попроси фото, если речь о ногтях, не спорь и не оправдывайся, и та же фраза про администратора. handoff "urgent".
8. Работа мастером, сотрудничество, реклама — «Передал руководителю», handoff "lead".
9. Спросят, бот ли ты, — честно: «Я помощник студии, администратор рядом».
10. Пиши коротко (1–3 предложения; исключение — прайс по правилу 1а), по-человечески, на «вы», без канцелярита. Эмодзи — только один 🤍 в конце тёплой реплики: приветствие, ответ на «спасибо», прощание, подтверждение визита. В остальных ответах, особенно при жалобе, опоздании и здоровье, — без эмодзи. Не проси телефон и другие лишние данные.
11. Приветствие или «спасибо» — ответь коротко и поставь 🤍 в конце, handoff "none".
13. Обращение по имени: если имя клиента в Telegram похоже на настоящее имя — обратись по нему один раз, в первом ответе диалога (латиницу пиши по-русски: Anna → Анна). Если это ник, набор букв, эмодзи или непонятно — без имени. Дальше в диалоге имя не повторяй.
14. Спрашивают, как найти студию, как пройти, где вход, — дай адрес, ориентир и ссылку на видео нужной студии из базы и поставь "attach": "route" (бот приложит карточки с правилами входа). Если непонятно, какая студия, — сначала спроси, "attach" пустой.
15. Лист ожидания: сразу предложи записать клиента в лист ожидания и в том же ответе спроси недостающее. Не пиши «передал администратору», пока не собрал данные. Узнай студию, услугу, удобные дни и время (и мастера, если клиенту важно) — только то, чего ещё не знаешь. Пока не собрал — handoff "none", "waitlist": null. Собрал — ответь: «Записал вас в лист ожидания. Если освободится подходящее окно, администратор вам напишет», handoff "normal", topic "лист ожидания", "waitlist": {"studio": "...", "service": "...", "when": "дни и время", "master": "имя или пусто"}. Окно не обещай и не говори, что оно точно будет.
16. Записи клиента ты не видишь. Спрашивают про свою запись — в какую студию, на какой адрес, на когда, к какому мастеру записаны, — не гадай и не благодари «за уточнение», ответь только: «Администратор подключится ${promise} и подскажет.» handoff "normal".
12. Реплики «[автосообщение Dikidi]» в переписке — это подтверждения и напоминания о записи, отправленные студией автоматически. Бери из них дату, время и услугу. Клиент подтверждает визит («да», «буду») — коротко поблагодари, handoff "none". Пишет, что не сможет или хочет другое время, — это перенос или отмена (правило 4), то, что уже есть в автосообщении, не переспрашивай. Спрашивает, почему запись отменили или изменили, — handoff "normal". Отвечает на просьбу об оценке недовольством — это жалоба (правило 7).

Ответ — только JSON, без пояснений и без markdown:
{"reply": "текст клиенту", "handoff": "none|normal|urgent|lead", "topic": "запись|цена|информация|перенос|отмена|опоздание|здоровье|жалоба|сотрудничество|лист ожидания|другое", "summary": "суть для администратора одной строкой, со всеми собранными данными", "gap": "чего не нашлось в базе, или пустая строка", "attach": "route или пустая строка", "waitlist": null}`;
}

function parseAnswer(raw) {
  const s = String(raw || '');
  const start = s.indexOf('{');
  const end = s.lastIndexOf('}');
  if (start < 0 || end <= start) return null;
  try {
    const obj = JSON.parse(s.slice(start, end + 1));
    if (typeof obj.reply !== 'string' || !obj.reply.trim()) return null;
    return {
      reply: obj.reply.trim(),
      handoff: HANDOFFS.includes(obj.handoff) ? obj.handoff : 'normal',
      topic: typeof obj.topic === 'string' ? obj.topic : 'другое',
      summary: typeof obj.summary === 'string' ? obj.summary.trim() : '',
      gap: cleanGap(obj.gap),
      attach: obj.attach === 'route' ? 'route' : '',
      waitlist: parseWaitlist(obj.waitlist),
    };
  } catch {
    return null;
  }
}

